"""Extract the stock HyperOS images used by the aristotle build.

The Xiaomi 13T build reuses, unmodified, the vendor-side partitions of the
stock HyperOS 3 firmware (vendor, odm, vendor_dlkm, odm_dlkm, system_dlkm) and
ships the platform firmware (preloader, lk, tee, modem, ...) inside the ROM so
that the vendor and the firmware always match.

usage (from the root of the Android source tree):
    device/xiaomi/aristotle/extract-images.py <stock OTA zip | payload.bin | dir with *.img>

Recommended input: the official full OTA ("Recovery ROM") zip
    aristotle_eea_global-ota_full-OS3.0.5.0.WMFEUXM-user-16.0-96845cc20f.zip
from https://cdnorg.d.miui.com/OS3.0.5.0.WMFEUXM/

The result is written to vendor/xiaomi/aristotle-images/.
"""

import argparse
import bz2
import hashlib
import lzma
import os
import re
import shutil
import struct
import sys
import zipfile

DEVICE = 'aristotle'
EXPECTED_BUILD = 'OS3.0.5.0.WMFEUXM'

# Dynamic partitions taken as-is from the stock firmware.
PREBUILT_PARTITIONS = [
    'odm',
    'odm_dlkm',
    'system_dlkm',
    'vendor',
    'vendor_dlkm',
]

# Platform firmware, flashed by update_engine to both slots like stock does.
FIRMWARE_PARTITIONS = [
    'apusys',
    'audio_dsp',
    'ccu',
    'dpm',
    'gpueb',
    'gz',
    'lk',
    'logo',
    'mcf_ota',
    'mcupm',
    'md1img',
    'mvpu_algo',
    'pi_img',
    'preloader_raw',
    'scp',
    'spmfw',
    'sspm',
    'tee',
    'vcp',
]

# Boot images, only needed to refresh the kernel prebuilts in the device tree.
KERNEL_PARTITIONS = [
    'boot',
    'vendor_boot',
    'dtbo',
]

HEADER = """#
# SPDX-FileCopyrightText: The LineageOS Project
# SPDX-License-Identifier: Apache-2.0
#
# Automatically generated by device/xiaomi/aristotle/extract-images.py
# Source: {source}
#
"""


# --------------------------------------------------------------------------
# Minimal payload.bin (full OTA) reader, without protobuf dependency
# --------------------------------------------------------------------------
def _varint(b, i):
    result = shift = 0
    while True:
        c = b[i]
        i += 1
        result |= (c & 0x7F) << shift
        shift += 7
        if not c & 0x80:
            return result, i


def _fields(b):
    i, n = 0, len(b)
    while i < n:
        key, i = _varint(b, i)
        field, wire = key >> 3, key & 7
        if wire == 0:
            value, i = _varint(b, i)
        elif wire == 1:
            value = struct.unpack_from('<Q', b, i)[0]
            i += 8
        elif wire == 2:
            length, i = _varint(b, i)
            value = b[i : i + length]
            i += length
        elif wire == 5:
            value = struct.unpack_from('<I', b, i)[0]
            i += 4
        else:
            raise ValueError(f'unsupported protobuf wire type {wire}')
        yield field, value


def _parse_partition(b):
    part = {'name': '', 'ops': [], 'size': 0}
    for f, v in _fields(b):
        if f == 1:
            part['name'] = v.decode()
        elif f == 7:  # new_partition_info
            part['size'] = dict(_fields(v)).get(1, 0)
        elif f == 8:  # operations
            op = {'type': 0, 'off': 0, 'len': 0, 'dst': []}
            for of, ov in _fields(v):
                if of == 1:
                    op['type'] = ov
                elif of == 2:
                    op['off'] = ov
                elif of == 3:
                    op['len'] = ov
                elif of == 6:
                    ext = dict(_fields(ov))
                    op['dst'].append((ext.get(1, 0), ext.get(2, 0)))
            part['ops'].append(op)
    return part


def _open_payload(path):
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as z:
            info = z.getinfo('payload.bin')
            if info.compress_type != zipfile.ZIP_STORED:
                sys.exit('payload.bin inside the zip is compressed, unsupported')
            try:
                meta = z.read('META-INF/com/android/metadata').decode()
            except KeyError:
                meta = ''
        f = open(path, 'rb')
        f.seek(info.header_offset)
        local = f.read(30)
        name_len, extra_len = struct.unpack_from('<HH', local, 26)
        return f, info.header_offset + 30 + name_len + extra_len, meta
    return open(path, 'rb'), 0, ''


def extract_payload(path, out_dir, wanted):
    f, base, meta = _open_payload(path)
    for line in meta.splitlines():
        if line.startswith(('post-build=', 'pre-device=')):
            print(f'  {line}')
    if meta and EXPECTED_BUILD not in meta:
        print(f'WARNING: this tree is tuned for {EXPECTED_BUILD}, '
              'the given OTA is a different build', file=sys.stderr)
    if meta and f'pre-device={DEVICE}' not in meta:
        sys.exit(f'ERROR: this OTA is not for {DEVICE}')

    f.seek(base)
    header = f.read(24)
    if header[:4] != b'CrAU':
        sys.exit('not an A/B OTA payload')
    version, manifest_size = struct.unpack('>QQ', header[4:20])
    sig_size = struct.unpack('>I', header[20:24])[0] if version >= 2 else 0
    manifest = f.read(manifest_size)
    data_base = base + 24 + manifest_size + sig_size

    block_size = 4096
    partitions = []
    for field, value in _fields(manifest):
        if field == 3:
            block_size = value
        elif field == 13:
            partitions.append(_parse_partition(value))

    found = set()
    for part in partitions:
        if part['name'] not in wanted:
            continue
        found.add(part['name'])
        dst_path = os.path.join(out_dir, part['name'] + '.img')
        print(f'  extracting {part["name"]} ({part["size"]} bytes)')
        with open(dst_path, 'wb') as out:
            out.truncate(part['size'])
            for op in part['ops']:
                kind = op['type']
                if kind in (6, 7):  # ZERO, DISCARD
                    continue
                f.seek(data_base + op['off'])
                data = f.read(op['len'])
                if kind == 0:  # REPLACE
                    pass
                elif kind == 1:  # REPLACE_BZ
                    data = bz2.decompress(data)
                elif kind == 8:  # REPLACE_XZ
                    data = lzma.decompress(data)
                elif kind == 14:  # REPLACE_ZSTD
                    try:
                        import zstandard
                    except ImportError:
                        sys.exit('python3 zstandard module required (pip install zstandard)')
                    data = zstandard.ZstdDecompressor().decompressobj().decompress(data)
                else:
                    sys.exit(f'unsupported operation {kind} in {part["name"]}: '
                             'use a FULL OTA, not an incremental one')
                pos = 0
                for start, num in op['dst']:
                    length = num * block_size
                    out.seek(start * block_size)
                    out.write(data[pos : pos + length])
                    pos += length
    return found


def copy_dir_images(src_dir, out_dir, wanted):
    found = set()
    for name in wanted:
        src = os.path.join(src_dir, name + '.img')
        if os.path.isfile(src):
            with open(src, 'rb') as f:
                if f.read(4) == b'\x3a\xff\x26\xed':
                    sys.exit(f'{src} is a sparse image, convert it with simg2img first')
            print(f'  copying {name}')
            shutil.copyfile(src, os.path.join(out_dir, name + '.img'))
            found.add(name)
    return found


# --------------------------------------------------------------------------
# Kernel prebuilts (--update-prebuilts)
# --------------------------------------------------------------------------
def _lz4_decompress(data):
    lz4 = shutil.which('lz4')
    if lz4:
        import subprocess
        return subprocess.run([lz4, '-dc'], input=data, stdout=subprocess.PIPE,
                              check=True).stdout
    try:
        import lz4.frame  # noqa: F401
        import lz4.block
    except ImportError:
        sys.exit('lz4 is required: install the lz4 package (apt install lz4)')
    # legacy lz4 format (used by mkbootimg): magic + [u32 size + block]...
    if data[:4] != b'\x02\x21\x4c\x18':
        return lz4.frame.decompress(data)
    out, pos = bytearray(), 4
    while pos + 4 <= len(data):
        size = struct.unpack_from('<I', data, pos)[0]
        if size == 0x184C2102:  # concatenated stream
            pos += 4
            continue
        pos += 4
        out += lz4.block.decompress(data[pos:pos + size], uncompressed_size=8 << 20)
        pos += size
    return bytes(out)


def _cpio_files(data):
    """Yield (name, mode, content) from a newc cpio archive."""
    pos = 0
    while pos + 110 <= len(data):
        if data[pos:pos + 6] not in (b'070701', b'070702'):
            raise ValueError('bad cpio header')
        fields = [int(data[pos + 6 + i * 8:pos + 14 + i * 8], 16) for i in range(13)]
        mode, filesize, namesize = fields[1], fields[6], fields[11]
        name_start = pos + 110
        name = data[name_start:name_start + namesize - 1].decode()
        pos = (name_start + namesize + 3) & ~3
        content = data[pos:pos + filesize]
        pos = (pos + filesize + 3) & ~3
        if name == 'TRAILER!!!':
            break
        yield name, mode, content


def _align(value, page):
    return (value + page - 1) // page * page


def update_prebuilts(boot_img, vendor_boot_img, dtbo_img, device_dir):
    kernel_dir = os.path.join(device_dir, 'prebuilts', 'kernel')
    modules_dir = os.path.join(device_dir, 'prebuilts', 'modules', 'vendor_ramdisk')

    # boot.img (header v3/v4): kernel starts at the second 4K page
    with open(boot_img, 'rb') as f:
        boot = f.read()
    if boot[:8] != b'ANDROID!':
        sys.exit('boot.img: bad magic')
    kernel_size, ramdisk_size = struct.unpack_from('<II', boot, 8)
    if struct.unpack_from('<I', boot, 40)[0] < 3:
        sys.exit('boot.img: unexpected header version')
    kernel = boot[4096:4096 + kernel_size]

    # vendor_boot.img (header v4)
    with open(vendor_boot_img, 'rb') as f:
        vboot = f.read()
    if vboot[:8] != b'VNDRBOOT':
        sys.exit('vendor_boot.img: bad magic')
    version, page = struct.unpack_from('<II', vboot, 8)
    vendor_ramdisk_size = struct.unpack_from('<I', vboot, 24)[0]
    cmdline = vboot[28:28 + 2048].rstrip(b'\0').decode()
    header_size, dtb_size = struct.unpack_from('<II', vboot, 2096)
    table_size, entry_num, entry_size, bootconfig_size = struct.unpack_from('<IIII', vboot, 2112)
    if version != 4:
        sys.exit(f'vendor_boot.img: unexpected header version {version}')
    ramdisk_off = _align(header_size, page)
    dtb_off = ramdisk_off + _align(vendor_ramdisk_size, page)
    table_off = dtb_off + _align(dtb_size, page)
    bootconfig_off = table_off + _align(table_size, page)
    dtb = vboot[dtb_off:dtb_off + dtb_size]
    bootconfig = vboot[bootconfig_off:bootconfig_off + bootconfig_size].decode(errors='replace')

    platform_ramdisk = None
    for i in range(entry_num):
        e = table_off + i * entry_size
        rd_size, rd_off, rd_type = struct.unpack_from('<III', vboot, e)
        if rd_type == 1 and platform_ramdisk is None:  # VENDOR_RAMDISK_TYPE_PLATFORM
            start = ramdisk_off + rd_off
            platform_ramdisk = vboot[start:start + rd_size]
    if platform_ramdisk is None:
        sys.exit('vendor_boot.img: no platform ramdisk found')

    modules = {}
    for name, mode, content in _cpio_files(_lz4_decompress(platform_ramdisk)):
        if name.startswith('lib/modules/') and (mode & 0o170000) == 0o100000:
            modules[os.path.basename(name)] = content
    if not any(n.endswith('.ko') for n in modules):
        sys.exit('vendor_boot.img: no kernel modules found in the platform ramdisk')

    # dtbo.img: keep the DT table, drop the partition padding
    with open(dtbo_img, 'rb') as f:
        dtbo = f.read()
    if dtbo[:4] != b'\xd7\xb7\xab\x1e':
        sys.exit('dtbo.img: bad magic')
    dtbo = dtbo[:_align(struct.unpack_from('>I', dtbo, 4)[0], 4096)]

    os.makedirs(os.path.join(kernel_dir, 'dtbs'), exist_ok=True)
    with open(os.path.join(kernel_dir, 'kernel'), 'wb') as f:
        f.write(kernel)
    with open(os.path.join(kernel_dir, 'dtbs', 'mt6895.dtb'), 'wb') as f:
        f.write(dtb)
    with open(os.path.join(kernel_dir, 'dtbo.img'), 'wb') as f:
        f.write(dtbo)
    shutil.rmtree(modules_dir, ignore_errors=True)
    os.makedirs(modules_dir)
    for name, content in sorted(modules.items()):
        with open(os.path.join(modules_dir, name), 'wb') as f:
            f.write(content)

    version_str = re.search(rb'Linux version [^\n\0]+', _lz4_decompress(kernel)
                            if kernel[:4] == b'\x02\x21\x4c\x18' else kernel)
    print(f'  kernel: {version_str.group(0).decode(errors="replace")[:80] if version_str else "unknown"}')
    print(f'  modules: {sum(n.endswith(".ko") for n in modules)}, dtb: {len(dtb)} bytes, '
          f'dtbo: {len(dtbo)} bytes')
    print(f'  vendor cmdline: "{cmdline}"')
    print('  bootconfig: ' + ' '.join(bootconfig.split()))
    print('  -> check BOARD_KERNEL_CMDLINE / BOARD_BOOTCONFIG and BOOT_SECURITY_PATCH in BoardConfig.mk')


def sha1(path):
    h = hashlib.sha1()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('source', help='stock OTA zip, payload.bin or directory with images')
    parser.add_argument('--android-root', default=None,
                        help='root of the Android source tree (default: auto-detect)')
    parser.add_argument('--no-firmware', action='store_true',
                        help='do not ship the platform firmware inside the ROM')
    parser.add_argument('--update-prebuilts', action='store_true',
                        help='also refresh the kernel, dtb, dtbo and vendor_boot modules '
                             'in the device tree (when moving to a new HyperOS release)')
    args = parser.parse_args()

    device_dir = os.path.dirname(os.path.realpath(__file__))
    root = args.android_root or os.path.realpath(os.path.join(device_dir, '..', '..', '..'))
    out_root = os.path.join(root, 'vendor', 'xiaomi', 'aristotle-images')
    img_dir = os.path.join(out_root, 'images')
    radio_dir = os.path.join(out_root, 'radio')

    shutil.rmtree(out_root, ignore_errors=True)
    os.makedirs(img_dir)
    os.makedirs(radio_dir)

    wanted = PREBUILT_PARTITIONS + ([] if args.no_firmware else FIRMWARE_PARTITIONS)
    if args.update_prebuilts:
        wanted += KERNEL_PARTITIONS
    tmp_dir = os.path.join(out_root, 'tmp')
    os.makedirs(tmp_dir)

    print(f'Extracting stock images from {args.source}')
    if os.path.isdir(args.source):
        found = copy_dir_images(args.source, tmp_dir, wanted)
    else:
        found = extract_payload(args.source, tmp_dir, wanted)

    missing = [p for p in PREBUILT_PARTITIONS if p not in found]
    if missing:
        sys.exit(f'ERROR: missing partitions in source: {" ".join(missing)}')

    if args.update_prebuilts:
        missing = [p for p in KERNEL_PARTITIONS if p not in found]
        if missing:
            sys.exit(f'ERROR: missing partitions in source: {" ".join(missing)}')
        print('Updating kernel prebuilts in ' + device_dir)
        update_prebuilts(*(os.path.join(tmp_dir, p + '.img') for p in KERNEL_PARTITIONS),
                         device_dir)

    firmware = [p for p in FIRMWARE_PARTITIONS if p in found]
    for name in PREBUILT_PARTITIONS:
        os.replace(os.path.join(tmp_dir, name + '.img'), os.path.join(img_dir, name + '.img'))
    for name in firmware:
        os.replace(os.path.join(tmp_dir, name + '.img'), os.path.join(radio_dir, name + '.img'))
    shutil.rmtree(tmp_dir)

    source = os.path.basename(os.path.normpath(args.source))
    with open(os.path.join(out_root, 'BoardConfigImages.mk'), 'w') as f:
        f.write(HEADER.format(source=source))
        if firmware:
            f.write('\nAB_OTA_PARTITIONS +=')
            for name in firmware:
                f.write(f' \\\n    {name}')
            f.write('\n')

    with open(os.path.join(out_root, 'Android.mk'), 'w') as f:
        f.write(HEADER.format(source=source))
        f.write('\nLOCAL_PATH := $(call my-dir)\n\nifeq ($(TARGET_DEVICE),aristotle)\n')
        for name in firmware:
            img = os.path.join(radio_dir, name + '.img')
            f.write(f'$(call add-radio-file-sha1-checked,radio/{name}.img,{sha1(img)})\n')
        f.write('endif\n')

    print(f'\nDone: {len(PREBUILT_PARTITIONS)} partition images and {len(firmware)} '
          f'firmware images written to {out_root}')


if __name__ == '__main__':
    main()
